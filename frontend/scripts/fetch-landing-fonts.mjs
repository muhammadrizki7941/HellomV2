// Downloads the Hellom Page fonts (Google Fonts, SIL Open Font License 1.1) into
// public/fonts/landing/: Latin subset only (covers Bahasa Indonesia), one variable file when the
// family has a weight axis. Self-hosted: shop pages never call Google (owner decision, Fase 0).
// Each font's OFL.txt from github.com/google/fonts is saved next to it (the OFL requires it).
// Keep in sync with backend App\Support\Landing\Fonts and landing-builder/editor/fonts.ts.
// Run from frontend/: node scripts/fetch-landing-fonts.mjs
import { mkdirSync, writeFileSync } from 'node:fs';

const OUT = new URL('../public/fonts/landing/', import.meta.url);
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';

// id, CSS family query, google/fonts repo dir
const FONTS = [
  ['jakarta', 'Plus+Jakarta+Sans:wght@400..800', 'plusjakartasans'],
  ['inter', 'Inter:wght@400..800', 'inter'],
  ['poppins', 'Poppins:wght@400;700', 'poppins'],
  ['montserrat', 'Montserrat:wght@400..800', 'montserrat'],
  ['dmsans', 'DM+Sans:wght@400..800', 'dmsans'],
  ['spacegrotesk', 'Space+Grotesk:wght@400..700', 'spacegrotesk'],
  ['playfair', 'Playfair+Display:wght@400..800', 'playfairdisplay'],
  ['lora', 'Lora:wght@400..700', 'lora'],
  ['dmserif', 'DM+Serif+Display', 'dmserifdisplay'],
  ['bebas', 'Bebas+Neue', 'bebasneue'],
  ['archivo', 'Archivo+Black', 'archivoblack'],
  ['caveat', 'Caveat:wght@400..700', 'caveat'],
];

mkdirSync(OUT, { recursive: true });
const licenses = [];
for (const [id, query, dir] of FONTS) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, { headers: { 'User-Agent': UA } })).text();
  // Only the "/* latin */" @font-face blocks (one per static weight, or one for a variable font).
  const blocks = css.split('/* ').filter((b) => b.startsWith('latin */'));
  if (blocks.length === 0) throw new Error(`${id}: no latin subset`);
  for (const block of blocks) {
    const url = /src: url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    const weight = /font-weight: ([\d ]+);/.exec(block)?.[1].trim();
    if (!url || !weight) throw new Error(`${id}: unexpected CSS`);
    // Variable: "400 800" → id.woff2; static weights → id-700.woff2
    const file = weight.includes(' ') || blocks.length === 1 ? `${id}.woff2` : `${id}-${weight}.woff2`;
    const data = Buffer.from(await (await fetch(url)).arrayBuffer());
    writeFileSync(new URL(file, OUT), data);
    console.log(`${file.padEnd(22)} ${String(Math.round(data.length / 1024)).padStart(4)} KB  weight ${weight}`);
  }
  const ofl = await fetch(`https://raw.githubusercontent.com/google/fonts/main/ofl/${dir}/OFL.txt`);
  if (!ofl.ok) throw new Error(`${id}: OFL.txt not found`);
  writeFileSync(new URL(`${id}.OFL.txt`, OUT), await ofl.text());
  licenses.push(`- \`${id}\` — ${decodeURIComponent(query.split(':')[0]).replace(/\+/g, ' ')} (\`${id}.OFL.txt\`)`);
}
writeFileSync(new URL('README.md', OUT), `# Hellom Page fonts

Self-hosted copies of Google Fonts families, Latin subset, used by Hellom Page shop pages and the
editor's font picker. All are licensed under the SIL Open Font License 1.1; each font's license
text (with its copyright notice) is in the matching \`*.OFL.txt\` file.

Generated by \`frontend/scripts/fetch-landing-fonts.mjs\`.

${licenses.join('\n')}
`);
console.log('done');
