// Generates src/styles/dashboard-dark.css: the dashboard's dark mode as a remap of Tailwind's
// color variables under html.hl-dark (every utility reads var(--color-*)), so pages need no
// dark: classes. Neutrals are inverted, light tints of hues become dark tints, dark shades
// become light. `.hl-light` (editor canvas, seller page previews) keeps the real colors.
//   node scripts/gen-dark-theme.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const theme = readFileSync(new URL('../node_modules/tailwindcss/theme.css', import.meta.url), 'utf8');
const palette = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (palette[m[1]] ??= {})[m[2]] = m[3].trim();

const NEUTRALS = ['zinc', 'slate', 'gray', 'neutral', 'stone'];
const HUES = ['red', 'rose', 'amber', 'yellow', 'emerald', 'green', 'blue', 'sky', 'violet', 'purple', 'orange', 'pink', 'indigo', 'teal', 'cyan', 'lime', 'fuchsia'];
const STEPS = ['50', '100', '200', '300', '400', '500', '600', '700', '800', '900', '950'];
const SURFACE = palette.zinc['900']; // cards (was white)

const dark = ['--color-white: ' + SURFACE, '--color-black: ' + palette.zinc['50']];
for (const n of NEUTRALS) {
  const p = palette[n];
  const map = {
    50: p['950'], // page background
    100: `color-mix(in oklab, ${p['900']} 60%, ${p['800']})`, // subtle fills
    200: `color-mix(in oklab, ${p['800']} 70%, ${p['700']})`, // borders
    300: p['700'], 400: p['400'], 500: `color-mix(in oklab, ${p['400']} 60%, ${p['300']})`, 600: p['300'], 700: p['200'], 800: p['100'], 900: p['50'], 950: '#fafafa',
  };
  for (const s of STEPS) dark.push(`--color-${n}-${s}: ${map[s]}`);
}
for (const h of HUES) {
  const p = palette[h];
  const tint = (pct) => `color-mix(in oklab, ${p['500']} ${pct}%, ${SURFACE})`;
  const map = { 50: tint(14), 100: tint(22), 200: tint(34), 300: tint(55), 500: p['400'], 600: p['400'], 700: p['300'], 800: p['200'], 900: p['100'], 950: p['50'] };
  for (const [s, v] of Object.entries(map)) dark.push(`--color-${h}-${s}: ${v}`);
}

const light = ['--color-white: #fff', '--color-black: #000'];
for (const n of [...NEUTRALS, ...HUES]) for (const s of STEPS) light.push(`--color-${n}-${s}: ${palette[n][s]}`);

// White text on solid colored buttons (bg-emerald-600 text-white …) stays white.
const solid = HUES.flatMap((h) => ['500', '600', '700'].map((s) => `html.hl-dark [class~="bg-${h}-${s}"]`)).join(',\n');
// …and those buttons keep their real shade (text-*-600 elsewhere is lightened for dark mode).
const solidShades = HUES.flatMap((h) => ['500', '600', '700'].map((s) => `--color-${h}-${s}: ${palette[h][s]}`));
// Black text on the yellow brand buttons stays black.
const brand = ['yellow', 'amber'].flatMap((h) => ['300', '400', '500'].map((s) => `html.hl-dark [class~="bg-${h}-${s}"]`)).join(',\n');
const scrims = [30, 35, 40, 50, 55, 60, 70, 80].map((o) => `html.hl-dark .bg-black\\/${o} { background-color: rgb(0 0 0 / ${o + 15}%); }`).join('\n');

const z = palette.zinc;
const css = `/* Generated by scripts/gen-dark-theme.mjs — do not edit by hand. */
/* Dashboard, light mode: grey secondary text (zinc-400/500) was below 4.5:1 on white. */
html.hl-dash:not(.hl-dark) {
  --color-zinc-400: color-mix(in oklab, ${z['500']} 85%, ${z['600']});
  --color-zinc-500: color-mix(in oklab, ${z['500']} 60%, ${z['600']});
}
html.hl-dark {
  color-scheme: dark;
  ${dark.join(';\n  ')};
}
html.hl-dash .hl-light {
  color-scheme: light;
  ${light.join(';\n  ')};
}
${solid} {
  --color-white: #fff;
  ${solidShades.join(';\n  ')};
}
${brand} {
  --color-black: #000;
  --color-white: #fff;
  --color-zinc-900: ${palette.zinc['900']};
  --color-zinc-950: ${palette.zinc['950']};
}
${scrims}
html.hl-dark img, html.hl-dark video { color-scheme: normal; }
`;
writeFileSync(new URL('../src/styles/dashboard-dark.css', import.meta.url), css);
console.log(`dashboard-dark.css: ${dark.length} dark vars, ${light.length} light vars`);
